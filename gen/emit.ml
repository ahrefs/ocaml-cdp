(* Print the library code.
   - type declarations with deriving attributes
   - sealed alias modules
   - domain, base and index files
   The roundtrip test is printed by Roundtrip. *)

open Naming
open Protocol

let render_header ~revision =
  spf "(* Generated by cdp-gen from Chrome DevTools Protocol %s. DO NOT EDIT. *)\n\n" revision

(* Deprecated / experimental flags as compiler attributes.
   - render_item_attributes: [@@...] after a type, module, command or event
   - render_field_attributes: [@...] after a record field
   - render_domain_attributes: [@@...] after a domain alias in the index
   - render_file_attributes: [@@@...] at the top of a domain file *)
let render_flags ~marker ~separator { deprecated; experimental; redirect } =
  let attribute name message = spf "%s[%s%s \"%s\"]" separator marker name message in
  let deprecated_attr =
    match deprecated, redirect with
    | false, None -> ""
    | true, None -> attribute "ocaml.deprecated" "deprecated in CDP"
    | true, Some domain -> attribute "ocaml.deprecated" (spf "deprecated in CDP, redirected to the %s domain" domain)
    | false, Some domain -> attribute "alert redirected" (spf "redirected to the %s domain in CDP" domain)
  in
  let experimental_attr =
    match experimental with
    | false -> ""
    | true -> attribute "alert experimental" "experimental in CDP, may change with Chrome"
  in
  deprecated_attr ^ experimental_attr

let render_item_attributes json = render_flags ~marker:"@@" ~separator:"\n" (flags_of_json json)

let render_field_attributes json = render_flags ~marker:"@" ~separator:" " (flags_of_json json)

let render_domain_attributes flags = render_flags ~marker:"@@" ~separator:"\n" flags

let render_file_attributes flags =
  match render_flags ~marker:"@@@" ~separator:"\n" flags with
  | "" -> ""
  | attrs -> spf "%s\n\n" (String.trim attrs)

let render_sealed_path ~dom ~id = spf "Cdp_base.%s.%s" (module_of_domain dom) (submodule_of_name id)

(* the OCaml type expression for a protocol type; codecs are derived *)
let rec map_type ~selected ~alias_tbl ~domain (type_json : Json.t) =
  match Util.member "$ref" type_json with
  | `String ref_string ->
    let dom, id = parse_ref ~current:domain ref_string in
    if not (List.mem dom selected) then
      failwith (spf "cdp-gen: ref %s from domain %s escapes the selected set" ref_string domain);
    if Hashtbl.mem alias_tbl (dom, id) then
      (* sealed primitive alias: lives in Base (a leaf), never cycles *)
      render_sealed_path ~dom ~id ^ ".t"
    else (
      let type_name = sanitize_lower id in
      match String.equal dom domain with
      | true -> type_name
      | false -> spf "%s.%s" (types_module_of_domain dom) type_name)
  | `Null ->
    (match Util.member "type" type_json with
    | `String "string" -> "string"
    | `String "integer" -> "int"
    | `String "number" -> "float"
    | `String "boolean" -> "bool"
    | `String "binary" -> "string" (* base64 on the wire *)
    | `String ("any" | "object") -> "Cdp_json.t"
    | `String "array" -> spf "%s list" (map_type ~selected ~alias_tbl ~domain (Util.member "items" type_json))
    | unexpected -> failwith (spf "cdp-gen: unhandled type in %s: %s" domain (Json.to_string unexpected)))
  | unexpected -> failwith (spf "cdp-gen: bad $ref: %s" (Json.to_string unexpected))

(* one type declaration body ("name = <shape> <per-decl attrs>"), chained
   later as "type a = .. and b = .." with one [@@deriving] for the group *)
type decl = {
  name : string;
  body : string;
}

let make_enum_decl ~type_name ~attrs values =
  let render_case value = spf "  | %s [@json.name %S]" (constructor_of_enum_value value) value in
  let known_cases = String.concat "\n" (List.map render_case values) in
  let unknown_case = "  | Other of Cdp_json.unknown [@json.catch_all]" in
  { name = type_name; body = spf "%s =\n%s\n%s\n[@@compact_variants]%s" type_name known_cases unknown_case attrs }

(* a record; fields with an inline enum get that enum hoisted to a named
   type (name chosen by ~hoist_name). Returns the hoisted decls and the record. *)
let make_record_decl ~selected ~alias_tbl ~domain ~type_name ~attrs ~hoist_name props =
  let field prop =
    let orig = get_string "name" prop in
    let optional = get_bool "optional" prop in
    let field_type, hoisted =
      match Inline_enum.of_prop prop with
      | Some inline_enum ->
        let enum = make_enum_decl ~type_name:(hoist_name orig) ~attrs:"" (Inline_enum.values inline_enum) in
        Inline_enum.field_type inline_enum ~enum_name:enum.name, Some enum
      | None -> map_type ~selected ~alias_tbl ~domain prop, None
    in
    let ocaml_type, wire_attrs =
      match optional with
      | false -> field_type, spf " [@key %S]" orig
      | true -> field_type ^ " option", spf " [@key %S] [@option] [@json.drop_default]" orig
    in
    let line = spf "  %s : %s%s%s;" (sanitize_lower orig) ocaml_type wire_attrs (render_field_attributes prop) in
    line, hoisted
  in
  let lines, hoisted = List.split (List.map field props) in
  ( List.filter_map Fun.id hoisted,
    {
      name = type_name;
      body = spf "%s = {\n%s\n}\n[@@allow_extra_fields]%s" type_name (String.concat "\n" lines) attrs;
    } )

let make_alias_decl ~type_name ~attrs type_expr = { name = type_name; body = spf "%s = %s%s" type_name type_expr attrs }

(* a named type from the "types" section (primitive aliases excluded) *)
let collect_named_type_decls ~selected ~alias_tbl ~domain type_def =
  let type_name = sanitize_lower (get_string "id" type_def) in
  let attrs = render_item_attributes type_def in
  match Util.member "enum" type_def, Util.member "properties" type_def with
  | `List values, _ -> [ make_enum_decl ~type_name ~attrs (List.map Util.to_string values) ]
  | `Null, `List (_ :: _ as props) ->
    let hoist_name = Hoisted_name.name_for_type_field ~type_id:(get_string "id" type_def) in
    let hoisted, record = make_record_decl ~selected ~alias_tbl ~domain ~type_name ~attrs ~hoist_name props in
    hoisted @ [ record ]
  | `Null, _ -> [ make_alias_decl ~type_name ~attrs (map_type ~selected ~alias_tbl ~domain type_def) ]
  | _unexpected_shape -> failwith ("cdp-gen: unhandled named type shape: " ^ get_string "id" type_def)

(* "type a = .. and b = .." with ONE [@@deriving] for the whole group *)
let render_chain ~deriving decls =
  match decls with
  | [] -> ""
  | _ :: _ ->
    spf "type %s\n[@@deriving %s]\n" (String.concat "\n\nand " (List.map (fun decl -> decl.body) decls)) deriving

let check_no_dup ~what names =
  let sorted = List.sort String.compare names in
  let rec go = function
    | first :: second :: _ when String.equal first second -> failwith (spf "cdp-gen: duplicate %s: %s" what first)
    | _ :: rest -> go rest
    | [] -> ()
  in
  go sorted

let render_sealed_module ~module_name ~prim ~attrs =
  let ml_ty, conv, eq_mod, prim_fn, show_expr =
    match prim with
    | "string" -> "string", "string", "String", "string", "Printf.sprintf \"%S\" value"
    | "integer" -> "int", "int", "Int", "int", "string_of_int value"
    | "number" -> "float", "float", "Float", "float", "string_of_float value"
    | "boolean" -> "bool", "bool", "Bool", "bool", "string_of_bool value"
    | unknown_prim -> failwith ("cdp-gen: unknown primitive: " ^ unknown_prim)
  in
  spf
    "module %s : sig\n\
    \  type t\n\
    \  val of_%s : %s -> t\n\
    \  val to_%s : t -> %s\n\
    \  val equal : t -> t -> bool\n\
    \  val compare : t -> t -> int\n\
    \  val pp : Format.formatter -> t -> unit\n\
    \  val show : t -> string\n\
    \  val of_json : Jsonkit.t -> t\n\
    \  val to_json : t -> Jsonkit.t\n\
     end = struct\n\
    \  type t = %s\n\
    \  let of_%s value = value\n\
    \  let to_%s value = value\n\
    \  let equal = %s.equal\n\
    \  let compare = %s.compare\n\
    \  let show (value : t) = %s\n\
    \  let pp fmt value = Format.pp_print_string fmt (show value)\n\
    \  let of_json = Jsonkit.Primitives.%s_of_json\n\
    \  let to_json = Jsonkit.Primitives.%s_to_json\n\
     end%s\n"
    module_name conv ml_ty conv ml_ty ml_ty conv conv eq_mod eq_mod show_expr prim_fn prim_fn attrs

(* primitive aliases of a domain with their primitive kind, in protocol order *)
let collect_domain_aliases ~alias_tbl (domain : domain) =
  List.filter_map
    (fun type_def ->
      Hashtbl.find_opt alias_tbl (domain.name, get_string "id" type_def) |> Option.map (fun prim -> type_def, prim))
    domain.types

let emit_base_file ~revision ~alias_tbl domains =
  let buf = Buffer.create 4096 in
  Buffer.add_string buf
    (spf
       "(* Generated by cdp-gen from Chrome DevTools Protocol %s. DO NOT EDIT. *)\n\
        (* Sealed modules for every primitive alias type. This file depends on\n\
       \   nothing, so alias references can never create a module cycle. *)\n\n"
       revision);
  List.iter
    (fun domain ->
      match collect_domain_aliases ~alias_tbl domain with
      | [] -> ()
      | aliases ->
        Buffer.add_string buf (spf "module %s = struct\n" (module_of_domain domain.name));
        List.iter
          (fun (type_def, prim) ->
            let module_name = submodule_of_name (get_string "id" type_def) in
            Buffer.add_string buf (render_sealed_module ~module_name ~prim ~attrs:(render_item_attributes type_def));
            Buffer.add_string buf "\n")
          aliases;
        Buffer.add_string buf "end\n\n")
    domains;
  Buffer.contents buf

let emit_types_file ~revision ~selected ~alias_tbl (domain : domain) =
  let buf = Buffer.create 4096 in
  Buffer.add_string buf (render_header ~revision);
  Buffer.add_string buf (render_file_attributes domain.flags);
  Buffer.add_string buf "open Jsonkit.Primitives\n\n";
  (* re-export sealed aliases so users write Cdp.Network.Request_id.t *)
  List.iter
    (fun (type_def, _prim) ->
      let module_name = submodule_of_name (get_string "id" type_def) in
      Buffer.add_string buf
        (spf "module %s = %s%s\n" module_name
           (render_sealed_path ~dom:domain.name ~id:(get_string "id" type_def))
           (render_item_attributes type_def)))
    (collect_domain_aliases ~alias_tbl domain);
  Buffer.add_string buf "\n";
  let named =
    List.filter (fun type_def -> not (Hashtbl.mem alias_tbl (domain.name, get_string "id" type_def))) domain.types
  in
  let decls = List.concat_map (collect_named_type_decls ~selected ~alias_tbl ~domain:domain.name) named in
  check_no_dup ~what:(spf "type name in %s_types" (sanitize_lower domain.name)) (List.map (fun decl -> decl.name) decls);
  Buffer.add_string buf (render_chain ~deriving:"json, show, eq" decls);
  Buffer.contents buf

(* A params or result record inside a command / event module.
   - hoisted enums first, in their own group: `make` cannot derive on variants
   - then the record with its own deriving list
   Returns the text and the type names it defines. *)
let render_record_block ~selected ~alias_tbl ~domain ~hoist_name ~type_name ~make props =
  let hoisted, record = make_record_decl ~selected ~alias_tbl ~domain ~type_name ~attrs:"" ~hoist_name props in
  let record_deriving = if make then "json, show, eq, make" else "json, show, eq" in
  ( spf "%s\n%s\n" (render_chain ~deriving:"json, show, eq" hoisted) (render_chain ~deriving:record_deriving [ record ]),
    List.map (fun decl -> decl.name) (hoisted @ [ record ]) )

(* Unit payload with a hand-written decoder.
   CDP answers {} for zero-return commands and params-less events,
   while a derived unit codec expects null. *)
let render_unit_block type_name =
  spf "type %s = unit [@@deriving show, eq]\n\nlet %s_of_json (_ignored_payload : Cdp_json.t) : %s = ()\n\n" type_name
    type_name type_name

let render_params_block ~selected ~alias_tbl ~domain ~hoist_name ~params ~returns =
  match params, returns with
  | [], `Event -> render_unit_block "params", [ "params" ]
  | [], `Returns _ -> "", []
  | props, _command_or_event ->
    render_record_block ~selected ~alias_tbl ~domain ~hoist_name ~type_name:"params" ~make:true props

(* The typed seam a transport uses.
   - event: the value it subscribes with
   - command: a value when there are no params, a function of the params record otherwise *)
let render_returns_block ~selected ~alias_tbl ~domain ~hoist_name ~params ~returns =
  match returns with
  | `Event -> "let event : params Cdp_event.t = { Cdp_event.name; parse = params_of_json }\n\n", []
  | `Returns props ->
    let result, names =
      match props with
      | [] -> render_unit_block "result", [ "result" ]
      | _returned_fields ->
        render_record_block ~selected ~alias_tbl ~domain ~hoist_name ~type_name:"result" ~make:false props
    in
    let command =
      match params with
      | [] -> "let command : result Cdp_command.t = { Cdp_command.name; params = None; parse = result_of_json }\n\n"
      | _params_fields ->
        "let command params : result Cdp_command.t =\n\
        \  { Cdp_command.name; params = Some (params_to_json params); parse = result_of_json }\n\n"
    in
    result ^ command, names

(* one submodule per command / event *)
let emit_item_module ~selected ~alias_tbl ~domain ~hoist_name ~module_name ~wire_name ~attrs ~params ~returns =
  let params_text, params_names = render_params_block ~selected ~alias_tbl ~domain ~hoist_name ~params ~returns in
  let returns_text, returns_names = render_returns_block ~selected ~alias_tbl ~domain ~hoist_name ~params ~returns in
  check_no_dup ~what:(spf "type name in %s.%s" domain module_name) (params_names @ returns_names);
  String.concat ""
    [
      spf "module %s = struct\n" module_name;
      spf "let name = %S\n\n" wire_name;
      params_text;
      returns_text;
      spf "end%s\n\n" attrs;
    ]

(* command/event submodules of a domain with their collision-resolved module
   names; shared by the domain-file emitter and the roundtrip-test emitter *)
let collect_item_modules ~alias_tbl (domain : domain) =
  let used =
    ref
      (List.map
         (fun (type_def, _prim) -> submodule_of_name (get_string "id" type_def))
         (collect_domain_aliases ~alias_tbl domain))
  in
  let claim ~fallback_suffix proposed =
    let name = if List.mem proposed !used then proposed ^ fallback_suffix else proposed in
    if List.mem name !used then failwith (spf "cdp-gen: module name collision in %s: %s" domain.name name);
    used := name :: !used;
    name
  in
  let commands =
    List.map
      (fun command ->
        claim ~fallback_suffix:"_command" (submodule_of_name (get_string "name" command)), `Command command)
      domain.commands
  in
  let events =
    List.map
      (fun event -> claim ~fallback_suffix:"_event" (submodule_of_name (get_string "name" event)), `Event event)
      domain.events
  in
  commands @ events

let emit_domain_file ~revision ~selected ~alias_tbl (domain : domain) =
  let buf = Buffer.create 4096 in
  Buffer.add_string buf (render_header ~revision);
  Buffer.add_string buf (render_file_attributes domain.flags);
  Buffer.add_string buf (spf "include %s\n" (types_module_of_domain domain.name));
  Buffer.add_string buf "open Jsonkit.Primitives\n\n";
  let domain_type_names = Hoisted_name.collect_domain_type_names domain in
  List.iter
    (fun (module_name, item) ->
      let hoist_name = Hoisted_name.name_for_item_field ~domain_type_names ~item_name:module_name in
      match item with
      | `Command command ->
        Buffer.add_string buf
          (emit_item_module ~selected ~alias_tbl ~domain:domain.name ~hoist_name ~module_name
             ~wire_name:(spf "%s.%s" domain.name (get_string "name" command))
             ~attrs:(render_item_attributes command) ~params:(get_list "parameters" command)
             ~returns:(`Returns (get_list "returns" command)))
      | `Event event ->
        Buffer.add_string buf
          (emit_item_module ~selected ~alias_tbl ~domain:domain.name ~hoist_name ~module_name
             ~wire_name:(spf "%s.%s" domain.name (get_string "name" event))
             ~attrs:(render_item_attributes event) ~params:(get_list "parameters" event) ~returns:`Event))
    (collect_item_modules ~alias_tbl domain);
  Buffer.contents buf

(* cdp.ml: the module users open. Cdp.Network -> Cdp_network etc. *)
let emit_index ~revision domains =
  let buf = Buffer.create 512 in
  Buffer.add_string buf (render_header ~revision);
  Buffer.add_string buf "(* Index: users write Cdp.Network, Cdp.Page, ... *)\n\n";
  Buffer.add_string buf
    "module Json = Cdp_json\n\
     module Command = Cdp_command\n\
     module Event = Cdp_event\n\
     module Envelope = Cdp_envelope\n\
     module Base = Cdp_base\n";
  List.iter
    (fun (domain : domain) ->
      Buffer.add_string buf
        (spf "module %s = %s%s\nmodule %s_types = %s%s\n" (module_of_domain domain.name)
           (domain_module_of_domain domain.name) (render_domain_attributes domain.flags) (module_of_domain domain.name)
           (types_module_of_domain domain.name) (render_domain_attributes domain.flags)))
    domains;
  Buffer.contents buf
