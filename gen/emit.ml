(* Everything that prints OCaml: type declarations with their deriving
   attributes, sealed alias modules, and the per-domain / base / index files. *)

open Naming
open Protocol

let spf = Printf.sprintf

(* protocol revision stamped into generated headers; read from the REVISION
   file living next to the protocol JSON (written by `cdp-gen fetch`) *)
let revision = ref "unknown"

let header () = spf "(* Generated by cdp-gen from Chrome DevTools Protocol %s. DO NOT EDIT. *)\n\n" !revision

(* deprecated / experimental -> item attributes appended to a declaration *)
let item_attrs json =
  (if jbool "deprecated" json then "\n[@@ocaml.deprecated \"deprecated in CDP\"]" else "")
  ^ if jbool "experimental" json then "\n[@@alert experimental \"experimental in CDP, may change with Chrome\"]" else ""

let sealed_path ~dom ~id = spf "Cdp_base.%s.%s" (module_of_domain dom) (submodule_of_name id)

(* the OCaml type expression for a protocol type; codecs are derived *)
let rec map_type ~selected ~alias_tbl ~domain (type_json : Json.t) =
  match Util.member "$ref" type_json with
  | `String ref_string ->
    let dom, id = parse_ref ~current:domain ref_string in
    if not (List.mem dom selected) then
      failwith (spf "cdp-gen: ref %s from domain %s escapes the selected set" ref_string domain);
    if Hashtbl.mem alias_tbl (dom, id) then
      (* sealed primitive alias: lives in Base (a leaf), never cycles *)
      sealed_path ~dom ~id ^ ".t"
    else (
      let type_name = sanitize_lower id in
      match dom = domain with
      | true -> type_name
      | false -> spf "%s.%s" (types_module_of_domain dom) type_name)
  | `Null ->
    (match Util.member "type" type_json with
    | `String "string" -> "string"
    | `String "integer" -> "int"
    | `String "number" -> "float"
    | `String "boolean" -> "bool"
    | `String "binary" -> "string" (* base64 on the wire *)
    | `String ("any" | "object") -> "Cdp_json.t"
    | `String "array" -> spf "%s list" (map_type ~selected ~alias_tbl ~domain (Util.member "items" type_json))
    | unexpected -> failwith (spf "cdp-gen: unhandled type in %s: %s" domain (Json.to_string unexpected)))
  | unexpected -> failwith (spf "cdp-gen: bad $ref: %s" (Json.to_string unexpected))

(* one type declaration body ("name = <shape> <per-decl attrs>"), chained
   later as "type a = .. and b = .." with one [@@deriving] for the group *)
type decl = {
  name : string;
  body : string;
}

let enum_decl ~tname ~attrs values =
  let ctors = List.map (fun value -> value, constructor_of_enum_value value) values in
  let names = List.map snd ctors in
  let dedup = List.sort_uniq String.compare names in
  (match List.length dedup = List.length names with
  | true -> ()
  | false -> failwith (spf "cdp-gen: constructor collision in enum %s: %s" tname (String.concat "," names)));
  {
    name = tname;
    body =
      spf "%s =\n%s\n  | Other of Cdp_json.unknown [@json.catch_all]\n[@@compact_variants]%s" tname
        (ctors |> List.map (fun (value, ctor) -> spf "  | %s [@json.name %S]" ctor value) |> String.concat "\n")
        attrs;
  }

(* a record; fields with an inline enum get that enum hoisted to a named
   type (name chosen by ~hoist_name). Returns hoisted decls ++ [record]. *)
let record_decl ~selected ~alias_tbl ~domain ~tname ~attrs ~hoist_name props =
  let hoisted = ref [] in
  let hoist raw_name enum_json =
    let hname = hoist_name raw_name in
    let values = List.map Util.to_string (Util.to_list enum_json) in
    hoisted := !hoisted @ [ enum_decl ~tname:hname ~attrs:"" values ];
    hname
  in
  let fields =
    List.map
      (fun prop ->
        let orig = jstr "name" prop in
        let fname = sanitize_lower orig in
        let optional = jbool "optional" prop in
        let field_type =
          match Util.member "enum" prop with
          | `List _ as enum_json -> hoist orig enum_json
          | _no_inline_enum ->
          match Util.member "type" prop, Util.member "items" prop with
          | `String "array", (`Assoc _ as items) when Util.member "enum" items <> `Null ->
            spf "%s list" (hoist orig (Util.member "enum" items))
          | _not_an_enum_array -> map_type ~selected ~alias_tbl ~domain prop
        in
        let attrs = spf " [@key %S]%s" orig (if optional then " [@option] [@json.drop_default]" else "") in
        spf "  %s : %s%s%s;" fname field_type (if optional then " option" else "") attrs)
      props
  in
  !hoisted
  @ [ { name = tname; body = spf "%s = {\n%s\n}\n[@@allow_extra_fields]%s" tname (String.concat "\n" fields) attrs } ]

let alias_decl ~tname ~attrs type_expr = { name = tname; body = spf "%s = %s%s" tname type_expr attrs }

(* a named type from the "types" section (primitive aliases excluded) *)
let named_type_decls ~selected ~alias_tbl ~domain type_def =
  let tname = sanitize_lower (jstr "id" type_def) in
  let attrs = item_attrs type_def in
  match Util.member "enum" type_def, Util.member "properties" type_def with
  | `List values, _ -> [ enum_decl ~tname ~attrs (List.map Util.to_string values) ]
  | `Null, `List (_ :: _ as props) ->
    let parent = camel_to_snake (jstr "id" type_def) in
    record_decl ~selected ~alias_tbl ~domain ~tname ~attrs
      ~hoist_name:(fun field -> parent ^ "_" ^ camel_to_snake field)
      props
  | `Null, _ -> [ alias_decl ~tname ~attrs (map_type ~selected ~alias_tbl ~domain type_def) ]
  | _ -> failwith ("cdp-gen: unhandled named type shape: " ^ jstr "id" type_def)

(* "type a = .. and b = .." with ONE [@@deriving] for the whole group *)
let render_chain ~deriving decls =
  match decls with
  | [] -> ""
  | _ :: _ ->
    spf "type %s\n[@@deriving %s]\n" (String.concat "\n\nand " (List.map (fun decl -> decl.body) decls)) deriving

let check_no_dup ~what names =
  let sorted = List.sort String.compare names in
  let rec go = function
    | first :: second :: _ when first = second -> failwith (spf "cdp-gen: duplicate %s: %s" what first)
    | _ :: rest -> go rest
    | [] -> ()
  in
  go sorted

let sealed_module ~mname ~prim ~attrs =
  let ml_ty, conv, eq_mod, prim_fn, show_expr =
    match prim with
    | "string" -> "string", "string", "String", "string", "Printf.sprintf \"%S\" value"
    | "integer" -> "int", "int", "Int", "int", "string_of_int value"
    | "number" -> "float", "float", "Float", "float", "string_of_float value"
    | "boolean" -> "bool", "bool", "Bool", "bool", "string_of_bool value"
    | unknown_prim -> failwith ("cdp-gen: unknown primitive: " ^ unknown_prim)
  in
  spf
    "module %s : sig\n\
    \  type t\n\
    \  val of_%s : %s -> t\n\
    \  val to_%s : t -> %s\n\
    \  val equal : t -> t -> bool\n\
    \  val compare : t -> t -> int\n\
    \  val pp : Format.formatter -> t -> unit\n\
    \  val show : t -> string\n\
    \  val of_json : Jsonkit.t -> t\n\
    \  val to_json : t -> Jsonkit.t\n\
     end = struct\n\
    \  type t = %s\n\
    \  let of_%s value = value\n\
    \  let to_%s value = value\n\
    \  let equal = %s.equal\n\
    \  let compare = %s.compare\n\
    \  let show (value : t) = %s\n\
    \  let pp fmt value = Format.pp_print_string fmt (show value)\n\
    \  let of_json = Jsonkit.Primitives.%s_of_json\n\
    \  let to_json = Jsonkit.Primitives.%s_to_json\n\
     end%s\n"
    mname conv ml_ty conv ml_ty ml_ty conv conv eq_mod eq_mod show_expr prim_fn prim_fn attrs

(* primitive aliases of a domain, in protocol order *)
let domain_aliases ~alias_tbl (domain : domain) =
  List.filter (fun type_def -> Hashtbl.mem alias_tbl (domain.name, jstr "id" type_def)) domain.types

let emit_base_file ~alias_tbl domains =
  let buf = Buffer.create 4096 in
  Buffer.add_string buf
    (spf
       "(* Generated by cdp-gen from Chrome DevTools Protocol %s. DO NOT EDIT. *)\n\
        (* Sealed modules for every primitive alias type. This file depends on\n\
       \   nothing, so alias references can never create a module cycle. *)\n\n"
       !revision);
  List.iter
    (fun domain ->
      match domain_aliases ~alias_tbl domain with
      | [] -> ()
      | aliases ->
        Buffer.add_string buf (spf "module %s = struct\n" (module_of_domain domain.name));
        List.iter
          (fun type_def ->
            let prim = Hashtbl.find alias_tbl (domain.name, jstr "id" type_def) in
            let mname = submodule_of_name (jstr "id" type_def) in
            Buffer.add_string buf (sealed_module ~mname ~prim ~attrs:(item_attrs type_def));
            Buffer.add_string buf "\n")
          aliases;
        Buffer.add_string buf "end\n\n")
    domains;
  Buffer.contents buf

let emit_types_file ~selected ~alias_tbl (domain : domain) =
  let buf = Buffer.create 4096 in
  Buffer.add_string buf (header ());
  Buffer.add_string buf "open Jsonkit.Primitives\n\n";
  (* re-export sealed aliases so users write Cdp.Network.Request_id.t *)
  List.iter
    (fun type_def ->
      let mname = submodule_of_name (jstr "id" type_def) in
      Buffer.add_string buf
        (spf "module %s = %s%s\n" mname (sealed_path ~dom:domain.name ~id:(jstr "id" type_def)) (item_attrs type_def)))
    (domain_aliases ~alias_tbl domain);
  Buffer.add_string buf "\n";
  let named =
    List.filter (fun type_def -> not (Hashtbl.mem alias_tbl (domain.name, jstr "id" type_def))) domain.types
  in
  let decls = List.concat_map (named_type_decls ~selected ~alias_tbl ~domain:domain.name) named in
  check_no_dup ~what:(spf "type name in %s_types" (sanitize_lower domain.name)) (List.map (fun decl -> decl.name) decls);
  Buffer.add_string buf (render_chain ~deriving:"json, show, eq" decls);
  Buffer.contents buf

(* one submodule per command / event *)
let emit_item_module ~selected ~alias_tbl ~domain ~mname ~wire_name ~attrs ~params ~returns =
  let buf = Buffer.create 1024 in
  Buffer.add_string buf (spf "module %s = struct\n" mname);
  Buffer.add_string buf (spf "let name = %S\n\n" wire_name);
  let local_names = ref [] in
  let block ~tname ~make props =
    let decls =
      record_decl ~selected ~alias_tbl ~domain ~tname ~attrs:"" ~hoist_name:(fun field -> sanitize_lower field) props
    in
    local_names := !local_names @ List.map (fun decl -> decl.name) decls;
    (* hoisted enums first (own group: `make` cannot derive on variants),
       then the record with its own deriving list *)
    let hoisted, record =
      match List.rev decls with
      | record :: rev_hoisted -> List.rev rev_hoisted, record
      | [] -> assert false
    in
    Buffer.add_string buf (render_chain ~deriving:"json, show, eq" hoisted);
    Buffer.add_string buf "\n";
    Buffer.add_string buf
      (render_chain ~deriving:(if make then "json, show, eq, make" else "json, show, eq") [ record ]);
    Buffer.add_string buf "\n"
  in
  (match params, returns with
  | [], `Event ->
    (* params-less event: unit payload, mirroring zero-return commands *)
    local_names := !local_names @ [ "params" ];
    Buffer.add_string buf
      "type params = unit [@@deriving show, eq]\n\nlet params_of_json (_ignored_payload : Cdp_json.t) : params = ()\n\n"
  | [], `Returns _ -> ()
  | props, _command_or_event -> block ~tname:"params" ~make:true props);
  (match returns with
  | `Event ->
    (* the typed seam a transport subscribes with *)
    Buffer.add_string buf "let event : params Cdp_event.t = { Cdp_event.name; parse = params_of_json }\n\n"
  | `Returns props ->
    (match props with
    | [] ->
      (* zero-return command. CDP answers {} while derived unit codecs expect
         null, so the json decoder stays hand-written. *)
      local_names := !local_names @ [ "result" ];
      Buffer.add_string buf
        "type result = unit [@@deriving show, eq]\n\n\
         let result_of_json (_ignored_payload : Cdp_json.t) : result = ()\n\n"
    | _returned_fields -> block ~tname:"result" ~make:false props);
    (* the typed seam a transport sends: a value when there are no params,
       a function of the params record otherwise *)
    (match params with
    | [] ->
      Buffer.add_string buf
        "let command : result Cdp_command.t = { Cdp_command.name; params = None; parse = result_of_json }\n\n"
    | _params_fields ->
      Buffer.add_string buf
        "let command params : result Cdp_command.t =\n\
        \  { Cdp_command.name; params = Some (params_to_json params); parse = result_of_json }\n\n"));
  check_no_dup ~what:(spf "type name in %s.%s" domain mname) !local_names;
  Buffer.add_string buf (spf "end%s\n\n" attrs);
  Buffer.contents buf

(* command/event submodules of a domain with their collision-resolved module
   names; shared by the domain-file emitter and the roundtrip-test emitter *)
let item_modules ~alias_tbl (domain : domain) =
  let used =
    ref (List.map (fun type_def -> submodule_of_name (jstr "id" type_def)) (domain_aliases ~alias_tbl domain))
  in
  let claim ~fallback_suffix proposed =
    let name = if List.mem proposed !used then proposed ^ fallback_suffix else proposed in
    if List.mem name !used then failwith (spf "cdp-gen: module name collision in %s: %s" domain.name name);
    used := name :: !used;
    name
  in
  let commands =
    List.map
      (fun command -> claim ~fallback_suffix:"_command" (submodule_of_name (jstr "name" command)), `Command command)
      domain.commands
  in
  let events =
    List.map
      (fun event -> claim ~fallback_suffix:"_event" (submodule_of_name (jstr "name" event)), `Event event)
      domain.events
  in
  commands @ events

let emit_domain_file ~selected ~alias_tbl (domain : domain) =
  let buf = Buffer.create 4096 in
  Buffer.add_string buf (header ());
  Buffer.add_string buf (spf "include %s\n" (types_module_of_domain domain.name));
  Buffer.add_string buf "open Jsonkit.Primitives\n\n";
  List.iter
    (fun (mname, item) ->
      match item with
      | `Command command ->
        Buffer.add_string buf
          (emit_item_module ~selected ~alias_tbl ~domain:domain.name ~mname
             ~wire_name:(domain.name ^ "." ^ jstr "name" command)
             ~attrs:(item_attrs command) ~params:(jlist "parameters" command)
             ~returns:(`Returns (jlist "returns" command)))
      | `Event event ->
        Buffer.add_string buf
          (emit_item_module ~selected ~alias_tbl ~domain:domain.name ~mname
             ~wire_name:(domain.name ^ "." ^ jstr "name" event)
             ~attrs:(item_attrs event) ~params:(jlist "parameters" event) ~returns:`Event))
    (item_modules ~alias_tbl domain);
  Buffer.contents buf

(* cdp.ml: the module users open. Cdp.Network -> Cdp_network etc. *)
let emit_index domains =
  let buf = Buffer.create 512 in
  Buffer.add_string buf (header ());
  Buffer.add_string buf "(* Index: users write Cdp.Network, Cdp.Page, ... *)\n\n";
  Buffer.add_string buf
    "module Json = Cdp_json\n\
     module Command = Cdp_command\n\
     module Event = Cdp_event\n\
     module Envelope = Cdp_envelope\n\
     module Base = Cdp_base\n";
  List.iter
    (fun (domain : domain) ->
      Buffer.add_string buf
        (spf "module %s = %s\nmodule %s_types = %s\n" (module_of_domain domain.name)
           (domain_module_of_domain domain.name) (module_of_domain domain.name) (types_module_of_domain domain.name)))
    domains;
  Buffer.contents buf
