(* Load and check the protocol JSON.
   - domain model
   - checks: refs exist, no type cycle
   - primitive-alias table
   - file IO *)

module Json = Yojson.Safe
module Util = Yojson.Safe.Util

let spf = Printf.sprintf

type flags = {
  deprecated : bool;
  experimental : bool;
  redirect : string option; (* the domain that now handles this command *)
}

type domain = {
  name : string;
  types : Json.t list;
  commands : Json.t list;
  events : Json.t list;
  flags : flags;
  description : string option;
}

let get_string field json = Util.member field json |> Util.to_string

let get_list field json =
  match Util.member field json with
  | `Null -> []
  | value -> Util.to_list value

let has_field field json =
  match Util.member field json with
  | `Null -> false
  | _present -> true

let get_bool field json =
  match Util.member field json with
  | `Null -> false
  | `Bool value -> value
  | wrong_type -> failwith (spf "cdp-gen: field %S must be a boolean, got %s" field (Json.to_string wrong_type))

let flags_of_json json =
  {
    deprecated = get_bool "deprecated" json;
    experimental = get_bool "experimental" json;
    redirect = Util.member "redirect" json |> Util.to_string_option;
  }

let description_of_json json = Util.member "description" json |> Util.to_string_option

let is_letter ch = Naming.is_upper ch || Naming.is_lower ch
let is_digit = Naming.is_digit

(* a domain name becomes output file names and module names in generated
   code, so anything beyond a plain identifier (a path separator, a comment
   opener) must be rejected before it reaches the filesystem *)
let check_domain_name name =
  let plain =
    String.length name > 0 && is_letter name.[0] && String.for_all (fun ch -> is_letter ch || is_digit ch) name
  in
  if plain then name
  else failwith (spf "cdp-gen: domain name %S is not a plain identifier (letters and digits only)" name)

let load_domains path =
  let json = Json.from_file path in
  Util.member "domains" json
  |> Util.to_list
  |> List.map (fun domain_json ->
    {
      name = check_domain_name (get_string "domain" domain_json);
      types = get_list "types" domain_json;
      commands = get_list "commands" domain_json;
      events = get_list "events" domain_json;
      flags = flags_of_json domain_json;
      description = description_of_json domain_json;
    })

let read_file path =
  let input = open_in path in
  Fun.protect
    ~finally:(fun () -> close_in input)
    (fun () -> String.trim (really_input_string input (in_channel_length input)))

let remove_if_exists path = if Sys.file_exists path then Sys.remove path

(* Write next to the target, then rename.
   - a failed write never leaves a half-written target
   - the temporary file is removed on failure *)
let write_file path contents =
  let tmp = path ^ ".tmp" in
  let output = open_out tmp in
  match
    output_string output contents;
    close_out output
  with
  | () -> Sys.rename tmp path
  | exception error ->
    close_out_noerr output;
    remove_if_exists tmp;
    raise error

let generated_header_prefix = "(* Generated by cdp-gen"

let is_generated_file path =
  match open_in path with
  | exception Sys_error _unreadable -> false
  | input ->
    let first_line =
      match input_line input with
      | line -> line
      | exception End_of_file -> ""
    in
    close_in input;
    String.starts_with ~prefix:generated_header_prefix first_line

(* files of a domain dropped from the selection would stay behind and break
   the next build; remove every generated cdp_*.ml this run does not produce *)
let remove_stale_generated_files ~outdir ~fresh =
  let is_stale name =
    String.starts_with ~prefix:"cdp_" name
    && Filename.check_suffix name ".ml"
    && (not (List.mem name fresh))
    && is_generated_file (Filename.concat outdir name)
  in
  Sys.readdir outdir
  |> Array.to_list
  |> List.filter is_stale
  |> List.sort String.compare
  |> List.iter (fun name ->
    Sys.remove (Filename.concat outdir name);
    Printf.printf "removed stale %s\n" name)

let parse_ref ~current ref_string =
  match String.index_opt ref_string '.' with
  | None -> current, ref_string
  | Some dot -> String.sub ref_string 0 dot, String.sub ref_string (dot + 1) (String.length ref_string - dot - 1)

(* every "$ref" string reachable inside a json fragment *)
let rec collect_refs (json : Json.t) acc =
  match json with
  | `List items -> List.fold_left (fun acc item -> collect_refs item acc) acc items
  | `Assoc fields ->
    List.fold_left
      (fun acc (key, value) ->
        match key, value with
        | "$ref", `String ref_string -> ref_string :: acc
        | _not_a_ref -> collect_refs value acc)
      acc fields
  | _scalar -> acc

let is_primitive_alias type_def =
  let has field = has_field field type_def in
  if has "enum" || has "properties" || has "items" then None
  else (
    match Util.member "type" type_def with
    | `String (("string" | "integer" | "number" | "boolean") as prim) -> Some prim
    | _not_a_primitive -> None)

(* (domain, TypeId) -> primitive kind, for aliases like Network.RequestId *)
let build_alias_table domains =
  let table = Hashtbl.create 64 in
  List.iter
    (fun domain ->
      List.iter
        (fun type_def ->
          match is_primitive_alias type_def with
          | Some prim -> Hashtbl.replace table (domain.name, get_string "id" type_def) prim
          | None -> ())
        domain.types)
    domains;
  table

(* type-level cross-domain graph; edges to sealed aliases excluded because
   those references are routed through Base (a leaf). Must be a DAG. *)
let check_types_dag domains ~alias_tbl =
  let edges (domain : domain) =
    List.concat_map (fun type_def -> collect_refs type_def []) domain.types
    |> List.filter_map (fun ref_string ->
      let dom, id = parse_ref ~current:domain.name ref_string in
      match String.equal dom domain.name with
      | true -> None
      | false -> if Hashtbl.mem alias_tbl (dom, id) then None (* routed through Base *) else Some dom)
    |> List.sort_uniq String.compare
  in
  let graph = List.map (fun (domain : domain) -> domain.name, edges domain) domains in
  let visiting = Hashtbl.create 16
  and finished = Hashtbl.create 16 in
  let rec visit path node =
    if Hashtbl.mem finished node then ()
    else if Hashtbl.mem visiting node then
      failwith
        (spf
           "cdp-gen: type-level cycle between domains: %s. Sealed-alias routing through Base cannot break it; the \
            domains in the cycle must be merged into one compilation unit."
           (String.concat " -> " (List.rev (node :: path))))
    else begin
      Hashtbl.replace visiting node ();
      List.iter (visit (node :: path)) (Option.value (List.assoc_opt node graph) ~default:[]);
      Hashtbl.remove visiting node;
      Hashtbl.replace finished node ()
    end
  in
  List.iter (fun (domain : domain) -> visit [] domain.name) domains

(* a $ref to a type that exists nowhere would surface much later, as a
   compile error inside generated code; refuse with the referrer's name.
   Refs to types in loaded-but-unselected domains are left to the emitter's
   selection check, which names the missing domain. *)
let check_refs_exist ~all ~selected =
  let defined = Hashtbl.create 256 in
  List.iter
    (fun domain ->
      List.iter (fun type_def -> Hashtbl.replace defined (domain.name, get_string "id" type_def) ()) domain.types)
    all;
  List.iter
    (fun domain ->
      let check_fragment ~owner fragment =
        List.iter
          (fun ref_string ->
            let target_domain, target_id = parse_ref ~current:domain.name ref_string in
            match Hashtbl.mem defined (target_domain, target_id) with
            | true -> ()
            | false -> failwith (spf "cdp-gen: %s references %s.%s, which does not exist" owner target_domain target_id))
          (collect_refs fragment [])
      in
      List.iter
        (fun type_def -> check_fragment ~owner:(spf "%s.%s" domain.name (get_string "id" type_def)) type_def)
        domain.types;
      List.iter
        (fun command -> check_fragment ~owner:(spf "%s.%s" domain.name (get_string "name" command)) command)
        domain.commands;
      List.iter
        (fun event -> check_fragment ~owner:(spf "%s.%s" domain.name (get_string "name" event)) event)
        domain.events)
    selected
